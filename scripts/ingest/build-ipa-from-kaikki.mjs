// scripts/ingest/build-ipa-from-kaikki.mjs
//
// Populate words.ipa with REAL Finnish IPA sourced from kaikki.org (English
// Wiktionary, CC BY-SA) — replacing the invented "sounds-like" pronunciations
// (e.g. the old hyvä "HEE-vah"; the genuine IPA is /ˈhyʋæ/).
//
// It reads the app's existing vocabulary base_forms from
// supabase/seeds/01_vocabulary.sql, looks each one up in the streamed kaikki
// Finnish JSONL via parse-kaikki.mjs, and emits an idempotent SQL migration of
// UPDATE statements — ONLY for words kaikki actually provides IPA for. IPA is
// never invented; uncovered words are skipped and listed.
//
// Usage:
//   node scripts/ingest/build-ipa-from-kaikki.mjs [raw/kaikki-Finnish.jsonl]
//
// Writes:
//   supabase/migrations/20260607000003_word_ipa_from_kaikki.sql  (committed)
//   scripts/ingest/out/ipa_lookup_REVIEW.tsv                     (git-ignored)

import { readFileSync, mkdirSync, writeFileSync, existsSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseKaikki, primaryIpa, primaryGloss } from './parse-kaikki.mjs'
import { RAW_DIR, OUT_DIR } from './lib/io.mjs'

const INGEST_DIR = resolve(dirname(fileURLToPath(import.meta.url)))
const REPO_ROOT = resolve(INGEST_DIR, '..', '..')
const VOCAB_SQL = resolve(REPO_ROOT, 'supabase/seeds/01_vocabulary.sql')
const MIGRATION = resolve(REPO_ROOT, 'supabase/migrations/20260607000003_word_ipa_from_kaikki.sql')

/** SQL single-quote escape. */
const q = (s) => s.replace(/'/g, "''")

/** Extract the app's vocabulary base_forms (first quoted field of each VALUES row). */
function extractBaseForms(sqlPath) {
  const text = readFileSync(sqlPath, 'utf8')
  const forms = []
  const seen = new Set()
  for (const line of text.split('\n')) {
    // Data rows begin at column 0 with ('<base_form>', ...   (no apostrophes in Finnish base_forms)
    const m = line.match(/^\('([^']*)',/)
    if (!m) continue
    const bf = m[1]
    if (!seen.has(bf)) {
      seen.add(bf)
      forms.push(bf)
    }
  }
  return forms
}

async function main() {
  const rawArg = process.argv[2]
  const rawPath = rawArg
    ? rawArg.startsWith('/')
      ? rawArg
      : resolve(REPO_ROOT, rawArg)
    : resolve(RAW_DIR, 'kaikki-Finnish.jsonl')

  if (!existsSync(rawPath)) {
    console.error(`Missing kaikki dump: ${rawPath}\nDownload it first (see scripts/ingest/README.md).`)
    process.exit(1)
  }

  const baseForms = extractBaseForms(VOCAB_SQL)
  console.log(`Vocabulary base_forms: ${baseForms.length}`)

  // parseKaikki keys by LOWERCASED headword and filters on the supplied wordSet.
  const wordSet = new Set(baseForms.map((w) => w.toLowerCase()))
  console.log(`Streaming kaikki dump (this is large)…`)
  const map = await parseKaikki(rawPath, { wordSet })
  console.log(`kaikki entries matched: ${map.size}`)

  const updates = [] // { base_form, ipa, gloss }
  const noIpa = []   // in kaikki, but no IPA
  const notFound = [] // not in kaikki at all

  for (const bf of baseForms) {
    const entry = map.get(bf.toLowerCase())
    if (!entry) {
      notFound.push(bf)
      continue
    }
    const ipa = primaryIpa(entry)
    if (!ipa) {
      noIpa.push(bf)
      continue
    }
    updates.push({ base_form: bf, ipa, gloss: primaryGloss(entry) })
  }

  // ---- Emit the migration (idempotent UPDATEs; ONLY words.ipa) ----
  const header = `-- Real Finnish IPA for words.ipa, sourced from kaikki.org (English Wiktionary, CC BY-SA)
-- ---------------------------------------------------------------------------
-- GENERATED by scripts/ingest/build-ipa-from-kaikki.mjs — do not hand-edit.
-- Replaces the invented "sounds-like" pronunciations with genuine IPA, e.g.
-- hyvä -> /ˈhyʋæ/. Every value below is the IPA kaikki actually provides; no IPA
-- is invented. Words kaikki has no IPA for are intentionally left untouched.
--
-- Prerequisite: 20260607000002_add_word_ipa.sql (adds the words.ipa column).
-- Idempotent: re-running sets the same values. Additive only — touches ONLY
-- words.ipa; does not alter rows' other columns, auth, RLS, or billing.
-- Coverage: ${updates.length} of ${baseForms.length} vocabulary base_forms got real IPA.
-- ---------------------------------------------------------------------------

`
  const body = updates
    .map((u) => `UPDATE words SET ipa = '${q(u.ipa)}' WHERE base_form = '${q(u.base_form)}';`)
    .join('\n')
  writeFileSync(MIGRATION, header + body + '\n')

  // ---- Review TSV (git-ignored) ----
  if (!existsSync(OUT_DIR)) mkdirSync(OUT_DIR, { recursive: true })
  const tsv =
    'base_form\tipa\tgloss\n' +
    updates.map((u) => `${u.base_form}\t${u.ipa}\t${u.gloss}`).join('\n') +
    '\n'
  writeFileSync(resolve(OUT_DIR, 'ipa_lookup_REVIEW.tsv'), tsv)

  // ---- Report ----
  console.log(`\n=== IPA coverage ===`)
  console.log(`  got real IPA : ${updates.length} / ${baseForms.length}`)
  console.log(`  in kaikki, no IPA: ${noIpa.length}`)
  console.log(`  not in kaikki: ${notFound.length}`)

  const showcase = ['hyvä', 'työ', 'yö', 'ystävä', 'auto']
  console.log(`\n=== examples ===`)
  const shown = new Set()
  for (const w of showcase) {
    const u = updates.find((x) => x.base_form === w)
    if (u) {
      console.log(`  ${u.base_form} → ${u.ipa}   (${u.gloss})`)
      shown.add(u.base_form)
    }
  }
  for (const u of updates) {
    if (shown.size >= 10) break
    if (shown.has(u.base_form)) continue
    console.log(`  ${u.base_form} → ${u.ipa}   (${u.gloss})`)
    shown.add(u.base_form)
  }

  console.log(`\n=== skipped: not in kaikki (${notFound.length}) ===`)
  console.log('  ' + notFound.join(', '))
  console.log(`\n=== skipped: in kaikki but no IPA (${noIpa.length}) ===`)
  console.log('  ' + noIpa.join(', '))

  console.log(`\nWrote ${MIGRATION}`)
  console.log(`Wrote ${resolve(OUT_DIR, 'ipa_lookup_REVIEW.tsv')}`)
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
